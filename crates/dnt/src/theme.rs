use ratatui::style::{Color, Modifier, Style};
use ratatui::widgets::BorderType;

/// Colours used across the UI. Uses the terminal's ANSI palette so it follows
/// the user's terminal theme.
pub struct Theme {
    pub accent: Color,
    pub dim: Style,
    pub muted: Style,
    pub label: Style,
    pub heading: Style,
    pub heading_bar: Style,
    pub subheading: Style,
    pub title: Style,
    pub bullet: Style,
    pub link: Style,
    pub link_focused: Style,
    pub mechanic: Color,
    pub code: Color,
    pub inset_border: Style,
    pub quote_bar: Style,
    pub table_header: Style,
    pub table_alt: Style,
    pub selected: Style,
    pub selected_unfocused: Style,
    pub selection_marker: Style,
    pub border_type: BorderType,
    pub border: Style,
    pub border_focused: Style,
    pub pane_title: Style,
    pub bar: Style,
    pub brand: Style,
    pub tab_active: Style,
    pub tab_inactive: Style,
    pub category_active: Style,
    pub category_inactive: Style,
    pub keycap: Style,
    pub facet_source: Color,
    pub facet_tag: Color,
    pub facet_damage: Color,
    pub facet_level: Color,
    pub facet_text: Color,
}

impl Default for Theme {
    fn default() -> Self {
        let accent = Color::Yellow;
        Theme {
            accent,
            dim: Style::new().fg(Color::DarkGray),
            muted: Style::new().fg(Color::Gray),
            label: Style::new().fg(Color::DarkGray),
            heading: Style::new().fg(accent).add_modifier(Modifier::BOLD),
            heading_bar: Style::new().fg(accent),
            subheading: Style::new().add_modifier(Modifier::BOLD),
            title: Style::new().fg(accent).add_modifier(Modifier::BOLD),
            bullet: Style::new().fg(accent),
            link: Style::new().fg(Color::Cyan),
            link_focused: Style::new().fg(Color::Black).bg(Color::Cyan),
            mechanic: Color::Magenta,
            code: Color::Green,
            inset_border: Style::new().fg(Color::Blue),
            quote_bar: Style::new().fg(Color::DarkGray),
            table_header: Style::new().fg(accent).add_modifier(Modifier::BOLD),
            table_alt: Style::new(),
            selected: Style::new().bg(Color::DarkGray).add_modifier(Modifier::BOLD),
            selected_unfocused: Style::new().bg(Color::Black),
            selection_marker: Style::new().fg(accent).bg(Color::DarkGray),
            border_type: BorderType::Rounded,
            border: Style::new().fg(Color::DarkGray),
            border_focused: Style::new().fg(accent),
            pane_title: Style::new().fg(Color::Gray).add_modifier(Modifier::BOLD),
            bar: Style::new(),
            brand: Style::new().fg(Color::Black).bg(accent).add_modifier(Modifier::BOLD),
            tab_active: Style::new().fg(Color::Black).bg(Color::Gray).add_modifier(Modifier::BOLD),
            tab_inactive: Style::new().fg(Color::Gray),
            category_active: Style::new().fg(Color::Black).bg(Color::Cyan).add_modifier(Modifier::BOLD),
            category_inactive: Style::new().fg(Color::Gray),
            keycap: Style::new().fg(Color::White).bg(Color::DarkGray),
            facet_source: Color::Blue,
            facet_tag: Color::Green,
            facet_damage: Color::Red,
            facet_level: Color::Magenta,
            facet_text: Color::Yellow,
        }
    }
}
